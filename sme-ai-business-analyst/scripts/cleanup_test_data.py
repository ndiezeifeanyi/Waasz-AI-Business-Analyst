import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.database import get_db_session
from sqlalchemy import select, delete
from app.models.business import Business
from app.models.user import User
from app.models.transaction import Transaction
from app.models.confirmation import Confirmation
from app.models.extraction import AiExtraction
from app.models.message import WhatsAppMessage
from app.models.customer import Customer
from app.models.member import Member
from app.models.receipt_template import ReceiptTemplate

async def inspect_and_clean():
    async for db in get_db_session():
        b_res = await db.execute(select(Business).order_by(Business.created_at.asc()))
        all_bizs = b_res.scalars().all()
        print(f"=== TOTAL BUSINESSES FOUND: {len(all_bizs)} ===")

        test_biz_ids = []
        real_bizs = []

        for b in all_bizs:
            phone = b.phone_number or ""
            # Test numbers generated by tests use +2348099... with random hex
            is_mock_test = phone.startswith("2348099") or phone.startswith("+2348099")
            if is_mock_test:
                test_biz_ids.append(b.id)
                print(f"[TEST MOCK] ID={b.id} | Name={b.name} | Phone={phone} | Created={b.created_at}")
            else:
                real_bizs.append(b)
                print(f"[REAL USER] ID={b.id} | Name={b.name} | Phone={phone} | Created={b.created_at}")

        print(f"\nFound {len(test_biz_ids)} test mock businesses to delete.")
        print(f"Found {len(real_bizs)} real businesses to preserve.")

        if test_biz_ids:
            # Delete associated records for test businesses
            await db.execute(delete(Transaction).where(Transaction.business_id.in_(test_biz_ids)))
            await db.execute(delete(Confirmation).where(Confirmation.business_id.in_(test_biz_ids)))
            await db.execute(delete(AiExtraction).where(AiExtraction.business_id.in_(test_biz_ids)))
            await db.execute(delete(WhatsAppMessage).where(WhatsAppMessage.business_id.in_(test_biz_ids)))
            await db.execute(delete(Customer).where(Customer.business_id.in_(test_biz_ids)))
            await db.execute(delete(Member).where(Member.business_id.in_(test_biz_ids)))
            await db.execute(delete(ReceiptTemplate).where(ReceiptTemplate.business_id.in_(test_biz_ids)))
            await db.execute(delete(User).where(User.business_id.in_(test_biz_ids)))
            await db.execute(delete(Business).where(Business.id.in_(test_biz_ids)))
            print(f"Successfully cleaned up {len(test_biz_ids)} test mock businesses.")

        # Fix user 2348113179049 who was mistakenly named "I meant university fresher"
        for b in real_bizs:
            if "2348113179049" in (b.phone_number or ""):
                print(f"\nResetting erroneously named business: {b.id} ({b.name})")
                b.name = "WhatsApp Business 9049"
                b.is_provisional = True
                settings_dict = dict(b.settings or {})
                settings_dict["onboarding_stage"] = "awaiting_business_name"
                b.settings = settings_dict
                # Also reset template if exists
                tmpl_res = await db.execute(select(ReceiptTemplate).where(ReceiptTemplate.business_id == b.id))
                tmpl = tmpl_res.scalar_one_or_none()
                if tmpl:
                    tmpl.business_display_name = "WhatsApp Business 9049"
                print("Reset 2348113179049 to provisional business name.")

        await db.commit()
        print("\nAll database changes committed.")
        break

if __name__ == "__main__":
    asyncio.run(inspect_and_clean())
